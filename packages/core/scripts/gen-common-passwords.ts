import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { normalizePassword } from '../src/crypto/password.js';

// Writes src/crypto/common-passwords.ts from the vendored lists (spec §7.1, D16):
//
//   data/common-passwords.txt      SecLists Passwords/Common-Credentials/10k-most-common.txt (MIT; data/README.md)
//   data/id-common-passwords.txt   our own Indonesian entries
//
// as one string constant: every entry NFKC-normalized and lower-cased (as isCommonPassword compares), deduplicated
// in first-seen order, newline-joined. Run it after changing either list:
//
//   pnpm --filter @altis/core gen:common-passwords
//
// test/policy.test.ts fails while the generated file and the lists disagree.

const PACKAGE = path.resolve(import.meta.dirname, '..');

/** The lists, relative to the package, in the order their entries are taken. */
export const LIST_FILES = ['data/common-passwords.txt', 'data/id-common-passwords.txt'] as const;

/** The generated module, relative to the package. */
export const OUTPUT_FILE = 'src/crypto/common-passwords.ts';

/** The entries of list texts (one per line, LF or CRLF, blank lines skipped, nothing trimmed), as stored. */
export function buildCommonPasswords(texts: readonly string[]): string {
  const seen = new Set<string>();
  for (const text of texts) {
    for (const line of text.split(/\r?\n/)) {
      if (line === '') continue;
      seen.add(normalizePassword(line).toLowerCase());
    }
  }
  return [...seen].join('\n');
}

/**
 * `list` as the body of a template literal: `\`, backquotes and `${` escaped, and as `\uXXXX` the control characters
 * other than LF, U+2028/U+2029 and surrogates.
 */
function templateBody(list: string): string {
  let out = '';
  for (let i = 0; i < list.length; i += 1) {
    const c = list[i]!;
    const code = list.charCodeAt(i);
    if (c === '\\' || c === '`' || (c === '$' && list[i + 1] === '{')) out += `\\${c}`;
    else if (
      (code < 0x20 && c !== '\n') ||
      code === 0x7f ||
      code === 0x2028 ||
      code === 0x2029 ||
      (code >= 0xd800 && code <= 0xdfff) // a lone surrogate would not survive UTF-8; a pair stays a pair
    ) {
      out += `\\u${code.toString(16).padStart(4, '0')}`;
    } else out += c;
  }
  return out;
}

/** The text of src/crypto/common-passwords.ts for `list`. */
export function renderModule(list: string): string {
  const count = list === '' ? 0 : list.split('\n').length;
  return [
    '// GENERATED by scripts/gen-common-passwords.ts from data/common-passwords.txt (SecLists, MIT: see',
    '// data/LICENSE-SecLists.txt and data/README.md) and data/id-common-passwords.txt. Do not edit by hand.',
    `// ${count} entries: NFKC, lower case, each once, newline-separated. policy.ts builds its Set on first use.`,
    '',
    `export const COMMON_PASSWORDS = \`${templateBody(list)}\`;`,
    '',
  ].join('\n');
}

function main(): void {
  const texts = LIST_FILES.map((file) => {
    const full = path.join(PACKAGE, file);
    if (!fs.existsSync(full)) {
      throw new Error(`${file} is missing: vendor it first (see data/README.md)`);
    }
    return fs.readFileSync(full, 'utf8');
  });
  const list = buildCommonPasswords(texts);
  fs.writeFileSync(path.join(PACKAGE, OUTPUT_FILE), renderModule(list));
  process.stdout.write(`${OUTPUT_FILE}: ${list.split('\n').length} entries\n`);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main();
}
